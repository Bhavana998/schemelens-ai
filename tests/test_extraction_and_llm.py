import pytest

from src.extraction.extractor import SchemeExtractor
from src.extraction.llm_provider import (
    GeminiLLMProvider,
    LLMProviderError,
    MockLLMProvider,
)
from src.models.schemas import DocumentContent, ExtractedPage, FieldStatus


def test_mock_llm_complete_extraction():
    extractor = SchemeExtractor(provider=MockLLMProvider())
    doc = DocumentContent(
        document_id="kisan_samriddhi_yojana.pdf",
        filename="kisan_samriddhi_yojana.pdf",
        file_hash="hash123",
        total_pages=1,
        pages=[ExtractedPage(page_number=1, text="Kisan Samriddhi Support Yojana Rs. 6,000 per year")],
        raw_full_text="Kisan Samriddhi Support Yojana Rs. 6,000 per year"
    )

    draft, metrics = extractor.extract_scheme_draft(doc)

    assert draft.scheme_name == "Kisan Samriddhi Support Yojana (Synthetic)"
    assert draft.fields["benefit_amount"].value == "Rs. 6,000 per year"
    assert draft.fields["benefit_amount"].status == FieldStatus.FOUND
    assert len(draft.fields["benefit_amount"].evidence) == 1
    assert metrics["estimated_cost_usd"] == 0.0


def test_missing_values_remain_missing():
    extractor = SchemeExtractor(provider=MockLLMProvider())
    doc = DocumentContent(
        document_id="mahila_swavalamban_yojana.pdf",
        filename="mahila_swavalamban_yojana.pdf",
        file_hash="hash456",
        total_pages=1,
        pages=[ExtractedPage(page_number=1, text="महिला स्वावलंबन स्वरोजगार योजना")],
        raw_full_text="महिला स्वावलंबन स्वरोजगार योजना"
    )

    draft, metrics = extractor.extract_scheme_draft(doc)

    # Deadline was deliberately omitted in the Hindi notification
    deadline_rec = draft.fields["deadline"]
    assert deadline_rec.value is None
    assert deadline_rec.status == FieldStatus.NOT_FOUND
    assert deadline_rec.note is not None
    assert len(deadline_rec.evidence) == 0

    # Official link was also omitted
    link_rec = draft.fields["official_link"]
    assert link_rec.value is None
    assert link_rec.status == FieldStatus.NOT_FOUND


def test_model_api_failure_does_not_fabricate_data():
    failing_provider = MockLLMProvider(simulate_failure=True, failure_message="API Gateway Timeout 504")
    extractor = SchemeExtractor(provider=failing_provider)
    doc = DocumentContent(
        document_id="test.pdf",
        filename="test.pdf",
        file_hash="abc",
        total_pages=1,
        pages=[ExtractedPage(page_number=1, text="Some text")],
        raw_full_text="Some text"
    )

    with pytest.raises(LLMProviderError) as exc_info:
        extractor.extract_scheme_draft(doc)

    assert "API Gateway Timeout 504" in str(exc_info.value)


