def test_gemini_response_schema_compatibility():
    """
    Regression test ensuring the JSON schema sent to Google Gemini in generationConfig.responseSchema
    contains zero instances of 'additionalProperties' or other unsupported OpenAPI keywords.
    """
    from src.models.schemas import RawExtractionPayload
    raw_schema = RawExtractionPayload.model_json_schema()

    # Raw schema generated by Pydantic contains additionalProperties on missing_fields_rationale (property 30)
    raw_json = json.dumps(raw_schema)
    assert "additionalProperties" in raw_json

    # Cleaned schema sent to Gemini must not have additionalProperties anywhere
    cleaned_schema = GeminiLLMProvider._clean_gemini_schema(raw_schema)
    cleaned_json = json.dumps(cleaned_schema)

    assert "additionalProperties" not in cleaned_json
    assert "$defs" not in cleaned_json
    assert "definitions" not in cleaned_json

    # Verify property 30 (missing_fields_rationale) has explicit properties defined and is not empty object
    props = cleaned_schema.get("properties", {})
    assert "missing_fields_rationale" in props
    mfr = props["missing_fields_rationale"]
    assert mfr.get("type") == "object"
    assert "properties" in mfr
    assert "deadline" in mfr["properties"]
    assert "additionalProperties" not in mfr

    # Verify standard core fields are preserved with their evidence & page references
    for f in ["scheme_name", "department", "benefit_amount", "deadline", "official_link"]:
        assert f in props
        assert f"{f}_evidence" in props
        assert f"{f}_page" in props


